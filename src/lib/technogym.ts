function stableId(key: string) {
  let hash = 14695981039346656037n;
  for (const c of key)
    hash = BigInt.asUintN(64, (hash ^ BigInt(c.codePointAt(0)!)) * 1099511628211n);
  return `11000000-0000-4000-8000-${hash.toString(16).padStart(16, '0').slice(-12)}`;
}
